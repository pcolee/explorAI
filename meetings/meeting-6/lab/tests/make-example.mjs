// Writes lab/example-run.js from examples/game-night-run.json, so the built-in example works with no fetch.
// Run from the repo root: node meetings/meeting-6/lab/tests/make-example.mjs
import fs from 'node:fs';

const src = new URL('../examples/game-night-run.json', import.meta.url);
const out = new URL('../example-run.js', import.meta.url);
const rec = JSON.parse(fs.readFileSync(src, 'utf8'));
const body = `// Generated by tests/make-example.mjs from examples/game-night-run.json. Do not edit by hand.\n// The recorded Game Night level 4 run that "See an example" opens in the walk-through.\nexport default ${JSON.stringify(rec, null, 1)};\n`;
fs.writeFileSync(out, body);
console.log(`wrote ${out.pathname} (${body.length} bytes)`);
